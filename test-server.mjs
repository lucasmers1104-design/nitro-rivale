// Mehrspieler-Server: Ablauf mit drei Clients prüfen (läuft komplett in einem Prozess)
import { createServer } from './server/server.mjs';
const { server, hub, port } = await createServer({ port: 0, quiet: true });
const URL = `ws://127.0.0.1:${port}/ws`;
let fails = 0;
const ok = (cond, msg) => { console.log((cond ? '  ✓ ' : '  ✗ ') + msg); if (!cond) fails++; };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
function client(name) {
  return new Promise((resolve, reject) => {
    const ws = new WebSocket(URL);
    const c = { ws, name, msgs: [], id: null, last: {} };
    c.send = (t, d = {}) => ws.send(JSON.stringify({ t, ...d }));
    c.take = (t) => c.msgs.filter((m) => m.t === t);
    c.waitFor = async (t, pred = () => true, ms = 3000) => {
      const t0 = Date.now();
      while (Date.now() - t0 < ms) { const m = c.msgs.find((x) => x.t === t && pred(x) && !x._seen); if (m) { m._seen = true; return m; } await wait(10); }
      throw new Error(`${name}: keine Nachricht ${t}`);
    };
    ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); c.last[m.t] = m; if (m.t === 'welcome') { c.id = m.id; resolve(c); } };
    ws.onerror = reject;
  });
}
const A = await client('Anna'), B = await client('Ben'), C = await client('Cem');
ok(A.id && B.id && C.id && A.id !== B.id, 'drei Verbindungen mit eigenen IDs');
A.send('create', { name: 'Anna', car: 'kaze', color: '#2f86f0' });
const r1 = await A.waitFor('room');
ok(/^[A-Z0-9]{5}$/.test(r1.code) && r1.host === A.id, `Raum erstellt (${r1.code}), Anna ist Gastgeberin`);
B.send('join', { code: 'ZZZZZ', name: 'Ben' });
ok((await B.waitFor('error')).code === 'notfound', 'falscher Code → nicht gefunden');
B.send('join', { code: 'AB', name: 'Ben' });
ok((await B.waitFor('error')).code === 'badCode', 'zu kurzer Code → Fehler');
B.send('join', { code: r1.code.toLowerCase(), name: 'Ben', car: 'rhino', color: '#ffbf2e' });
const r2 = await B.waitFor('room', (m) => m.players.length === 2);
ok(r2.players.map((p) => p.name).join() === 'Anna,Ben', 'Ben tritt bei (Code in Kleinbuchstaben geht auch)');
C.send('join', { code: r1.code, name: '<b>Cem</b>', car: 'brutus' });
const r3 = await A.waitFor('room', (m) => m.players.length === 3);
ok(r3.players[2].name === 'bCem/b', 'Name wird bereinigt (keine spitzen Klammern)');
B.send('settings', { level: 'pass' });
A.send('settings', { level: 'canyon', laps: 99, items: false, skill: 'profi' });
const r4 = await C.waitFor('room', (m) => m.settings.level === 'canyon');
ok(r4.settings.laps === 10 && r4.settings.items === false && r4.settings.skill === 'profi', 'nur Gastgeberin darf Einstellungen ändern, Runden begrenzt');
A.send('bots', { list: [{ name: 'Turbo-Tina', car: 'kaze', color: '#ffffff' }, { name: 'Rost-Rudi', car: 'xxx', color: 'rot' }] });
const r5 = await B.waitFor('room', (m) => m.bots.length === 2);
ok(r5.bots[1].car === 'brutus' && r5.bots[1].color === '#d9322b', 'Bots werden geprüft und ersetzt');
B.send('start');
await wait(150);
ok(!A.msgs.some((m) => m.t === 'load'), 'nur Gastgeberin kann starten');
A.send('start');
const L = await B.waitFor('load');
ok(L.race.grid.length === 5 && L.race.grid.filter((g) => g.bot).every((g) => g.owner === A.id), 'Startaufstellung: 2 Bots (gehören Anna) + 3 Fahrer');
ok(new Set(L.race.grid.map((g) => g.slot)).size === 5, 'jeder hat einen eigenen Startplatz');
const D = await client('Dora');
D.send('join', { code: r1.code, name: 'Dora' });
ok((await D.waitFor('error')).code === 'running', 'Beitritt während des Rennens wird abgelehnt');
A.send('ready', { race: L.race.id }); B.send('ready', { race: L.race.id });
await wait(150);
ok(!C.msgs.some((m) => m.t === 'countdown'), 'Ampel wartet, bis alle geladen haben');
C.send('ready', { race: L.race.id });
await C.waitFor('countdown');
ok(true, 'alle bereit → Countdown an alle');
A.send('s', { c: [['b1', 1, 2, 3], [A.id, 4, 5, 6], [B.id, 9, 9, 9]] });
const s1 = await B.waitFor('s');
ok(s1.c.length === 2 && !s1.c.some((x) => x[0] === B.id), 'Zustände werden weitergeleitet, fremde Autos herausgefiltert');
await wait(100);
ok(!A.msgs.some((m) => m.t === 's'), 'Absender bekommt seinen eigenen Zustand nicht zurück');
B.send('ev', { e: { type: 'imp', id: A.id, p: [0, 0, 0] } });
B.send('ev', { e: { type: 'imp', id: B.id, p: [1, 2, 3] } });
const e1 = await C.waitFor('ev');
ok(e1.e.id === B.id, 'Ereignisse nur für eigene Autos');
B.send('fin', { id: B.id, time: 61.2, best: 19.9 });
const f1 = await A.waitFor('fin');
ok(f1.id === B.id && f1.place === 1, 'Zieleinlauf wird an alle gemeldet');
B.send('fin', { id: B.id, time: 50 });
await wait(100);
ok(A.take('fin').length === 1, 'doppelte Zielmeldung wird ignoriert');
A.send('fin', { id: 'b1', time: 62 });
A.send('fin', { id: A.id, time: 63 });
C.send('fin', { id: C.id, time: 70 });
const end = await A.waitFor('end', () => true, 5000);
ok(end.finished.length === 4 && end.finished.find((f) => f.id === C.id).place === 4, 'alle Menschen im Ziel → Rennende mit Ergebnis');
const r6 = await B.waitFor('room', (m) => m.state === 'lobby');
ok(r6.state === 'lobby', 'Raum ist wieder in der Lobby');
D.send('join', { code: r1.code, name: 'Dora' });
const r7 = await D.waitFor('room', (m) => m.players.length === 4);
ok(r7.players.length === 4, 'nach dem Rennen kann wieder jemand beitreten');
A.send('leave');
const r8 = await B.waitFor('room', (m) => m.host !== A.id);
ok(r8.host === B.id && r8.players.length === 3, 'Gastgeberin geht → Ben wird Gastgeber');
// Verbindungsabbruch während des Rennens
B.send('start');
const L2 = await C.waitFor('load', (m) => m.race.id !== L.race.id);
for (const x of [B, C, D]) x.send('ready', { race: L2.race.id });
await C.waitFor('countdown');
D.ws.close();
const lf = await C.waitFor('left', (m) => m.id === D.id);
ok(lf.id === D.id, 'Abbruch eines Fahrers wird gemeldet');
B.send('fin', { id: B.id, time: 40 }); C.send('fin', { id: C.id, time: 41 });
await C.waitFor('end', (m) => m.race === L2.race.id, 6000);
ok(true, 'Rennen endet auch, wenn jemand weg ist');
// v8: Derby (Besitzer meldet "raus") und Ausscheiden (nur der Gastgeber), Tuning + Klasse
B.send('settings', { mode: 'derby', cls: 'B' });
B.send('profile', { name: 'Ben', car: 'vipera', tune: { aero: 3, engine: 9, tires: 'xxx', armor: 1, horn: 'train' } });
const r9 = await C.waitFor('room', (m) => m.settings.mode === 'derby' && m.settings.cls === 'B' && m.players.find((p) => p.id === B.id)?.car === 'vipera');
const bt = r9.players.find((p) => p.id === B.id).tune;
ok(bt.aero === 3 && bt.engine === 3 && bt.tires === 'street' && bt.horn === 'train', 'Tuning wird geprüft (Stufen begrenzt, unbekannte Reifen → Straße)');
B.send('bots', { list: [{ name: 'Crash-Carl', car: 'brummi', color: '#ffffff', tune: { armor: 2 } }] });
await C.waitFor('room', (m) => m.bots.length === 1);
B.send('start');
const L3 = await C.waitFor('load', (m) => m.race.mode === 'derby');
ok(L3.race.level === 'tal' && L3.race.cls === 'B' && L3.race.grid.find((g) => g.bot).tune.armor === 2, 'Derby lädt die Arena, Klasse + Bot-Tuning kommen mit');
for (const x of [B, C]) x.send('ready', { race: L3.race.id });
await C.waitFor('countdown');
C.send('out', { race: L3.race.id, id: B.id });
await wait(120);
ok(!C.msgs.some((m) => m.t === 'out'), 'fremdes Auto kann man im Derby nicht rausmelden');
B.send('out', { race: L3.race.id, id: 'b1', time: 12 });
const o1 = await C.waitFor('out', (m) => m.id === 'b1');
ok(o1.place === 3, 'Bot raus → Platz 3 von 3');
C.send('out', { race: L3.race.id, id: C.id, time: 20 });
const o2 = await B.waitFor('out', (m) => m.id === C.id);
const win = await B.waitFor('fin', (m) => m.winner);
ok(o2.place === 2 && win.id === B.id && win.place === 1, 'Letzter Überlebender gewinnt automatisch');
const end3 = await C.waitFor('end', (m) => m.race === L3.race.id, 7000);
ok(end3.finished.length === 3 && end3.finished.find((f) => f.id === 'b1').out, 'Derby-Ergebnis enthält die Ausgeschiedenen');
B.send('settings', { mode: 'elim' });
await C.waitFor('room', (m) => m.settings.mode === 'elim' && m.state === 'lobby');
B.send('start');
const L4 = await C.waitFor('load', (m) => m.race.mode === 'elim');
for (const x of [B, C]) x.send('ready', { race: L4.race.id });
await C.waitFor('countdown');
C.send('out', { race: L4.race.id, id: 'b1' });
await wait(120);
ok(!C.msgs.some((m) => m.t === 'out' && m.id === 'b1' && !m._seen), 'Ausscheiden: nur der Gastgeber entscheidet');
B.send('out', { race: L4.race.id, id: C.id });
const o3 = await B.waitFor('out', (m) => m.id === C.id);
ok(o3.place === 3, 'Gastgeber wirft den Letzten raus');
B.ws.close(); C.ws.close(); A.ws.close();
await wait(200);
ok(hub.rooms.size === 0, 'leere Räume werden gelöscht');
console.log(fails ? `${fails} Fehler` : 'alle Server-Tests bestanden');
server.close();
process.exit(fails ? 1 : 0);
